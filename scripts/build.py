def which_list(p):
    return p.get("list") or KIND_LIST.get(p["kind"])


def short(p, n=170):
    t = " ".join(str(p.get("notes", "")).split())
    m = re.search(r"(?<=[a-z0-9)\]])\. ", t)
    t = t[: m.start() + 1] if m and m.start() < n else t
    return (t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0] + " …").replace("|", "/")


def devs(p):
    return ", ".join(dev_names.get(s, s) for s in p["devices"])


REL_SHORT = {"fork_of": "fork of", "copy_of": "copy of", "port_of": "port of", "variant_of": "variant of", "builds_on": "builds on", "same_project": "same project as", "bundles": "bundles", "describes": "describes", "unclear": "cf.", "mod_for": "mod for", "uses_tool": "uses", "vendors": "vendors code from", "cites": "cites"}


def lrow(p, show_kind=False):
    st = "unverified entry" if p["status"] == "unverified" else p["status"]
    ver = str(p.get("version") or p.get("base_os") or "-").replace("|", "/")
    ver = ver if len(ver) <= 60 else ver[:59].rsplit(" ", 1)[0] + " …"
    kind = f"{p['kind']} | " if show_kind else ""
    rel = "; ".join(f"{REL_SHORT.get(x['type'], x['type'])} {x['id']}" for x in p.get("relations") or [])
    rel = f" <br>_{rel}_" if rel else ""
    return f"| **{p['name']}** ({p.get('author', '?')}){rel} | {kind}{devs(p)} | {short(p)} | {st} | {ver} | {row(p)} |"


