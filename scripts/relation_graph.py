"""Draw the relations between catalogue entries as a Mermaid graph for README.md.

build.py calls readme_with_graph() on every run. Standard library only.

- Nodes: entries that have at least one drawn relation (all others stay in the lists only).
  Each node shows the entry's name and its `license` field ("not recorded" when it has none).
- Colour: licence family (permissive, copyleft, public domain, none stated or not recorded).
- Boxes: the device family from data/devices.yml; an entry for more than one family goes in
  "Several device families".
- Edges: the `relations:` field, from the entry to the one it names. `unclear` relations are
  not drawn, because no source states what they are. Each edge's evidence follows it as a
  Mermaid comment.
"""
import re

START = "<!-- relation-graph:start - generated by scripts/build.py from data/projects.yml, do not edit by hand -->"
END = "<!-- relation-graph:end -->"

WORDS = {"fork_of": "fork of", "copy_of": "copy of", "port_of": "port of", "variant_of": "variant of",
         "builds_on": "builds on", "same_project": "same project as", "bundles": "bundles", "describes": "describes"}

# fill, stroke and text colour per licence family; readable on GitHub's light and dark pages
FAMILIES = {
    "permissive": ("#d9f2e3", "#2b7a4b", "#10301e"),
    "copyleft": ("#dde7fb", "#3460b0", "#13254a"),
    "public-domain": ("#f9ecc8", "#a07410", "#3d2c05"),
    "none": ("#ececec", "#7a7a7a", "#2a2a2a"),
}
FAMILY_NAMES = {"permissive": "permissive", "copyleft": "copyleft", "public-domain": "public domain",
                "none": "none stated or not recorded"}


def licence_family(text):
    """Sort a licence string into a family. Copyleft wins when a project names both kinds."""
    t = (text or "").lower()
    if re.search(r"\b(a|l)?gpl|\bmpl\b|\beupl\b|\bcc-by-sa\b", t):
        return "copyleft"
    if re.search(r"\bcc0\b|\bunlicense\b|public domain", t):
        return "public-domain"
    if re.search(r"\bmit\b|\bbsd\b|\bapache\b|\bisc\b|\bzlib\b|\bcc-by\b", t):
        return "permissive"
    return "none"


def _node_id(pid):
    return "n_" + re.sub(r"[^A-Za-z0-9]", "_", pid)


def _label(text):
    return str(text).replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")


def _short_name(name):
    name = " ".join(str(name).split())
    if len(name) > 32 and " (" in name:
        name = name.split(" (", 1)[0]
    return name if len(name) <= 40 else name[:39].rstrip() + "…"


def edges(projects):
    """(from id, type, to id, evidence) for every relation the graph draws."""
    ids = {p["id"] for p in projects}
    out = []
    for p in projects:
        for r in p.get("relations") or []:
            if r.get("type") in WORDS and r.get("id") in ids:
                out.append((p["id"], r["type"], r["id"], " ".join(str(r.get("evidence", "")).split())))
    return out


def mermaid(projects, devices):
    """The Mermaid source of the graph, and the number of nodes and edges in it."""
    byid = {p["id"]: p for p in projects}
    es = edges(projects)
    used = sorted({e[0] for e in es} | {e[2] for e in es}, key=lambda i: byid[i]["name"].lower())
    family_of = {d["slug"]: d.get("family") or d["name"] for d in devices}
    order = list(dict.fromkeys(family_of[d["slug"]] for d in devices)) + ["Several device families"]
    groups = {}
    for pid in used:
        fams = {family_of.get(s, s) for s in byid[pid].get("devices") or []}
        groups.setdefault(fams.pop() if len(fams) == 1 else "Several device families", []).append(pid)
    lines = ["flowchart LR"]
    for g in order + sorted(set(groups) - set(order)):
        if g not in groups:
            continue
        lines.append(f'  subgraph {_node_id("group " + g)}["{_label(g)}"]')
        for pid in groups[g]:
            p = byid[pid]
            lic = p.get("license") or "not recorded"
            lines.append(f'    {_node_id(pid)}["{_label(_short_name(p["name"]))}<br/>{_label(lic)}"]'
                         f':::{licence_family(p.get("license"))}')
        lines.append("  end")
    for a, kind, b, ev in es:
        lines.append(f'  {_node_id(a)} -- "{WORDS[kind]}" --> {_node_id(b)}')
        if ev:
            lines.append(f"  %% evidence: {ev}")
    for fam, (fill, stroke, colour) in FAMILIES.items():
        lines.append(f"  classDef {fam} fill:{fill},stroke:{stroke},color:{colour}")
    return "\n".join(lines), len(used), len(es)


def readme_with_graph(readme, projects, devices):
    """README text with the region between START and END replaced by the current graph."""
    src, n_nodes, n_edges = mermaid(projects, devices)
    block = (f"{START}\n\n{n_nodes} entries with {n_edges} relations. Colour: licence family "
             f"(green {FAMILY_NAMES['permissive']}, blue {FAMILY_NAMES['copyleft']}, "
             f"yellow {FAMILY_NAMES['public-domain']}, grey {FAMILY_NAMES['none']}).\n\n"
             f"```mermaid\n{src}\n```\n\n{END}")
    if START not in readme or END not in readme:
        raise ValueError("README.md has no relation-graph markers")
    head, rest = readme.split(START, 1)
    return head + block + rest.split(END, 1)[1], n_nodes, n_edges
