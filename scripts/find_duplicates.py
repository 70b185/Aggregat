#!/usr/bin/env python3
"""List facts in hardware/ that say the same thing in more than one place.

Reads export/aggregat.sqlite (run scripts/export_db.py first) and writes hardware/DUPLICATES.md: pairs of
facts from different files whose wording overlaps strongly, or that cite the same two or more addresses.
Each pair is a candidate for merging into one place and linking from the other. Generated; do not edit.

Usage: python3 scripts/find_duplicates.py [--min 0.45]
"""
from pathlib import Path
import argparse
import re
import sqlite3

ROOT = Path(__file__).resolve().parent.parent
ap = argparse.ArgumentParser()
ap.add_argument("--min", type=float, default=0.45, help="minimum word-overlap score (0..1)")
a = ap.parse_args()

STOP = set("""a an and are as at be been but by can do does for from has have in into is it its may more most
must no not of on one only or so than that the their them then there these they this to too two up was we were
what when which while who will with without you your also each other same if any all both per via""".split())
# Device and product names: lists of supported devices would otherwise look alike.
STOP |= set("""analog four rytm digitakt digitone syntakt heat keys mki mkii fx octatrack model cycles samples
machinedrum monomachine overbridge elektron""".split())


def words(t):
    t = re.sub(r"`[^`]*`", " ", t.lower())
    return {w for w in re.findall(r"[a-z][a-z0-9+-]{2,}", t) if w not in STOP}


con = sqlite3.connect(ROOT / "export/aggregat.sqlite")
rows = con.execute("SELECT id, file, line, section, text, evidence, sources, devices, addresses FROM facts").fetchall()
facts = [dict(zip(("id", "file", "line", "section", "text", "evidence", "sources", "devices", "addresses"), r)) for r in rows]
for f in facts:
    f["w"] = words(f["text"])
    f["a"] = set(x.lower() for x in (f["addresses"] or "").split(",") if x)
    f["d"] = set((f["devices"] or "").split(",")) - {""}

COMPARISON_PAGES = ("dt2-dn2-sharc-crosscheck.md",)


def links_to(x, y):
    # x carries a Markdown link to y's file, e.g. ](../common/recovery.md)
    return re.search(r"\]\([^)]*" + re.escape(y["file"].split("/")[-1]) + r"[)#]", x["text"]) is not None


pairs = []
for i, x in enumerate(facts):
    if len(x["w"]) < 6:
        continue
    for y in facts[i + 1:]:
        if x["file"] == y["file"] or len(y["w"]) < 6:
            continue
        if x["d"] and y["d"] and not (x["d"] & y["d"]):
            continue
        if x["file"].endswith(COMPARISON_PAGES) or y["file"].endswith(COMPARISON_PAGES):
            continue  # pages that restate findings on purpose, to compare them
        if links_to(x, y) or links_to(y, x):
            continue  # already consolidated: one fact points at the other's file
        inter = len(x["w"] & y["w"])
        score = inter / min(len(x["w"]), len(y["w"]))
        shared_addr = x["a"] & y["a"]
        if score >= a.min or len(shared_addr) >= 2:
            pairs.append((max(score, 0.5 if len(shared_addr) >= 2 else 0), x, y, shared_addr))
pairs.sort(key=lambda p: -p[0])

out = ["<!-- generated by scripts/find_duplicates.py - do not edit -->\n", "# Facts stated in more than one place\n",
       "Pairs of facts from different files under `hardware/` that overlap strongly in wording or cite the same "
       "addresses. Each is a candidate for keeping the fact in one file and linking to it from the other. Some pairs are "
       "intentional (a summary file pointing at a device file); some are two independent sources agreeing, which is "
       "worth keeping as a second confirmation. Pairs where one fact links to the other file count as consolidated and are left out. Score = shared content words / words of the shorter fact.\n",
       f"{len(pairs)} candidate pairs at score >= {a.min} or with two shared addresses.\n",
       "| Score | Fact A | Fact B | Shared addresses |", "|---|---|---|---|"]


def cell(f):
    t = f["text"] if len(f["text"]) <= 160 else f["text"][:159].rsplit(" ", 1)[0] + " …"
    return f"`{f['file'].replace('hardware/', '')}:{f['line']}` {t.replace('|', '/')}"


for s, x, y, sa in pairs:
    out.append(f"| {s:.2f} | {cell(x)} | {cell(y)} | {', '.join(sorted(sa)) or '-'} |")
(ROOT / "hardware/DUPLICATES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(pairs)} candidate pairs -> hardware/DUPLICATES.md")
