#!/usr/bin/env python3
"""Generate devices/<slug>.md and INDEX.md from data/projects.yml + data/devices.yml.

Usage: python3 scripts/build.py   (run from anywhere)
Needs PyYAML (pip install pyyaml).
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
projects_doc = yaml.safe_load((ROOT / "data" / "projects.yml").read_text(encoding="utf-8"))
devices = yaml.safe_load((ROOT / "data" / "devices.yml").read_text(encoding="utf-8"))["devices"]
projects = projects_doc["projects"]
checked = projects_doc["checked"]

GEN = "<!-- generated by scripts/build.py - edit data/*.yml instead -->\n"


def link(label, url):
    return f"[{label}]({url})"


def row(p):
    parts = []
    if p.get("repo"):
        parts.append(link("repo", p["repo"]))
    for k, v in (p.get("links") or {}).items():
        parts.append(link(k.replace("_", " "), v))
    return " · ".join(parts) or "-"


def table(rows):
    out = ["| Project | Kind | Status | Version / OS | Last seen | Links |", "|---|---|---|---|---|---|"]
    for p in sorted(rows, key=lambda x: str(x.get("last_activity") or ""), reverse=True):
        ver = "; ".join(x for x in (p.get("version"), p.get("base_os")) if x) or "-"
        ver = str(ver).replace("|", "/")
        out.append(
            f"| **{p['name']}** ({p.get('author', '?')}) | {p['kind']} | {p['status']} | {ver} | "
            f"{p.get('last_activity') or '-'} | {row(p)} |"
        )
    return "\n".join(out)


(ROOT / "devices").mkdir(exist_ok=True)
index = [GEN, "# Index by device\n", f"Data last verified: {checked}\n",
         "| Device | Projects |", "|---|---|"]
for d in devices:
    rows = [p for p in projects if d["slug"] in p["devices"]]
    real = [p for p in rows if p["kind"] not in ("request", "resource")]
    md = [GEN, f"# {d['name']}\n", f"Data last verified: {checked}\n"]
    if d.get("note"):
        md.append(f"> {' '.join(d['note'].split())}\n")
    if rows:
        md.append(table(rows))
        md.append("\n## Details\n")
        for p in rows:
            md.append(f"### {p['name']}\n")
            md.append(" ".join(str(p.get("notes", "")).split()) + "\n")
            md.append(f"_Sources: {', '.join(map(str, p.get('sources', [])))}_\n")
    else:
        md.append("No projects collected yet.\n")
    (ROOT / "devices" / f"{d['slug']}.md").write_text("\n".join(md), encoding="utf-8")
    index.append(f"| [{d['name']}](devices/{d['slug']}.md) | {len(real)} (+{len(rows) - len(real)} requests/resources) |")

(ROOT / "INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")
print(f"{len(projects)} projects, {len(devices)} devices")
