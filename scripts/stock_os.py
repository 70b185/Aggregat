#!/usr/bin/env python3
"""Generate hardware/STOCK-OS.md from data/stock-os.yml: which OS each project needs, how fast projects moved to a
new OS, and how to recognise every stock OS file by its SHA-256.

  python3 scripts/stock_os.py

Run by scripts/rebuild.py after build.py. The source is data/stock-os.yml; never edit the generated page.
"""
from pathlib import Path
import datetime

import yaml

ROOT = Path(__file__).resolve().parent.parent
MARK = "<!-- generated by scripts/stock_os.py - edit data/stock-os.yml, not this file -->"
USE = {"patch": "builds firmware from it", "donor": "takes parts of it for another device",
       "analysis": "emulator or research", "runs-on": "the unit must run it"}


def load():
    data = yaml.safe_load((ROOT / "data" / "stock-os.yml").read_text(encoding="utf-8"))
    devices = {d["slug"]: d["name"] for d in yaml.safe_load((ROOT / "data" / "devices.yml").read_text(encoding="utf-8"))["devices"]}
    projects = {p["id"]: p for p in yaml.safe_load((ROOT / "data" / "projects.yml").read_text(encoding="utf-8"))["projects"]}
    return data, devices, projects


def plink(pid, projects):
    p = projects.get(pid)
    return f"[{p['name']}](../p/{pid}/)" if p else pid


def date(x):
    return x if isinstance(x, datetime.date) else datetime.date.fromisoformat(str(x))


def newest(dev):
    """The newest release: the one with a release date, else the first listed (the file lists newest first)."""
    dated = [r for r in dev["releases"] if r.get("released")]
    return max(dated, key=lambda r: date(r["released"])) if dated else dev["releases"][0]


def camps(dev, devices, projects):
    top = newest(dev)
    rel = date(top["released"]) if top.get("released") else None
    name = devices[dev["device"]]
    out = [f"### {name}: newest OS {top['os']}" + (f" (since {rel})" if rel else ""), ""]
    groups = {}
    for s in dev["support"]:
        key = s["os"][0]
        groups.setdefault(key, []).append(s)
    order = [r["os"] for r in dev["releases"]]
    on_new = groups.get(top["os"], [])
    ported = [s for s in on_new if s.get("ported")]
    born = [s for s in on_new if not s.get("ported") and s["evidence"].startswith("first commit")]
    older = sum(len(v) for k, v in groups.items() if k != top["os"])
    out.append(f"{len(on_new)} projects accept {top['os']} ({len(ported)} moved from an older OS, {len(born)} started on "
               f"it); {older} need an older file. A unit runs one OS, so mods that need different versions cannot be "
               f"combined on it.")
    out.append("")
    out.append("| OS needed | Project | Use | Also accepts | Since | Note |")
    out.append("|---|---|---|---|---|---|")
    for k in sorted(groups, key=lambda v: order.index(v) if v in order else 99):
        for s in sorted(groups[k], key=lambda s: (s.get("ported") is None, str(s.get("ported") or ""), s["id"])):
            since = "-"
            if s.get("ported") and rel:
                days = (date(s["ported"]) - rel).days
                since = f"{s['ported']} ({days} days after the release)"
            elif k == top["os"] and s["evidence"].startswith("first commit"):
                since = "started on it (" + s["evidence"].removeprefix("first commit ") + ")"
            note = s.get("note", "")
            out.append(f"| {k} | {plink(s['id'], projects)} | {s['use']} | {', '.join(s['os'][1:]) or '-'} | {since} | "
                       f"{note} |")
    out.append("")
    return out, ported, rel


def main():
    data, devices, projects = load()
    out = [MARK, "# Stock OS files and which projects need which", ""]
    out.append("Most mods start from a stock OS file that the user downloads from Elektron, and accept exactly one "
               "version, recognised by its SHA-256. This page shows which version each project needs, how fast "
               "projects moved when Elektron released a new OS, and the hash of every stock file the projects "
               f"publish. Source: [`data/stock-os.yml`](../data/stock-os.yml); \"pinned by\" counts the catalogued "
               f"repositories that hold the exact value (searched {data['pinned_checked']}; vendored copies count).")
    out.append("")
    out.append("Always compare the hash against the file you actually downloaded. A matching hash only says you hold "
               "the file a project expects; it says nothing about whether the mod is safe. `[doc]`")
    out.append("")

    out.append("## Which OS the projects need (the releases of 2026-10-01)")
    out.append("")
    out.append("Elektron released Digitakt II 1.17, Digitone II 1.12 and Syntakt 1.42 on the same day. Use: "
               + "; ".join(f"*{k}* {v}" for k, v in USE.items()) + ".")
    out.append("")
    ports = []
    for dev in data["devices"]:
        if not dev.get("support"):
            continue
        lines, ported, rel = camps(dev, devices, projects)
        out += lines
        for s in ported:
            ports.append((devices[dev["device"]], newest(dev)["os"], s, (date(s["ported"]) - rel).days if rel else None))

    out.append("## How fast projects moved")
    out.append("")
    out.append("Only projects that existed before the release and moved to it. The date is the first commit that "
               "supports the new version.")
    out.append("")
    out.append("| Device | OS | Project | Days | Evidence |")
    out.append("|---|---|---|---|---|")
    for dev, os_, s, days in sorted(ports, key=lambda x: (x[3] if x[3] is not None else 999)):
        out.append(f"| {dev} | {os_} | {plink(s['id'], projects)} | {days} | {s['evidence']} |")
    out.append("")

    out.append("## Identifying stock files")
    out.append("")
    for dev in data["devices"]:
        out.append(f"### {devices[dev['device']]}")
        out.append("")
        out.append("| OS | File | SHA-256 | Pinned by | Sources |")
        out.append("|---|---|---|---|---|")
        notes = []
        for r in dev["releases"]:
            label = r["os"] + (f" ({r['model']})" if r.get("model") else "")
            if r.get("released"):
                label += f", {r['released']}"
            pins = r.get("pinned_by") or []
            ptxt = f"{len(pins)}: " + ", ".join(pins) if pins else "0"
            src = ", ".join("{" + k + "}" for k in r["sources"])
            out.append(f"| {label} | `{r['file']}` | `{r['sha256']}` | {ptxt} | {src} |")
            if r.get("released_note"):
                notes.append(f"- {r['os']}: release date from {r['released_note']}. `[doc]`")
            if r.get("other_sha256"):
                notes.append(f"- {r['os']}: another value, `{r['other_sha256']}`, is also seen. {r['other_note']} `[doc]`")
        out.append("")
        if notes:
            out += notes + [""]
    (ROOT / "hardware" / "STOCK-OS.md").write_text("\n".join(out), encoding="utf-8")
    n = sum(len(d["releases"]) for d in data["devices"])
    print(f"stock os: {n} files, {sum(len(d.get('support', [])) for d in data['devices'])} project links -> hardware/STOCK-OS.md")


if __name__ == "__main__":
    main()
