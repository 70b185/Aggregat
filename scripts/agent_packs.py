#!/usr/bin/env python3
"""Generated reading material for agents, from export/aggregat.sqlite (run scripts/export_db.py first).

Writes
  export/context/<device>.md         everything about one device in one file: safety rules, device rules, recovery,
                                     stock bugs, incidents, open conflicts, open tests, catalogued projects, and every
                                     fact (best evidence first), each with its stable id and file:line
  export/context/<device>-brief.md   the same without the fact list: what to read before touching the unit
  export/context/README.md           index with sizes and token estimates
  hardware/WEAK-EVIDENCE.md          facts without an evidence tag or tagged only [?]: a to-do list for contributors
  hardware/ADDRESS-MAP.md            every address named in a fact, per device, sorted, with the facts that name it

Deterministic: an unchanged database gives byte-identical files. Usage: python3 scripts/agent_packs.py
"""
from pathlib import Path
import json
import re
import sqlite3

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "export" / "aggregat.sqlite"
CTX = ROOT / "export" / "context"
REPO = "https://github.com/70b185/Aggregat/blob/master/"
MARK = "<!-- generated by scripts/agent_packs.py - edit the sources, not this file -->"
EV_ORDER = {"hw": 0, "emu": 1, "doc": 2, "?": 3, "": 4}

# free-text device columns (tasks, hypotheses) -> slugs; export_db's TEXT_DEVICE plus the short forms the research map uses
TEXT_DEVICE = [
    (r"\bDigitakt II\b|\bDT2\b", "digitakt-2"), (r"\bDigitone II\b|\bDN2\b", "digitone-2"),
    (r"\bDigitakt (mk1|MKI)\b|\bDT1\b|\bDT mk1\b|\bDT/DN mk1\b", "digitakt"),
    (r"\bDigitone (mk1|MKI)\b|\bDN1\b|\bDN mk1\b|\bDT/DN mk1\b|\bDigitone Keys\b", "digitone"),
    (r"\bSyntakt\b", "syntakt"), (r"\bAnalog Heat\b|\bHeat\b", "analog-heat"), (r"\bOctatrack\b", "octatrack"),
    (r"\bRytm\b", "analog-rytm"), (r"\bAnalog Four\b|\bA4\b|\bAnalog Keys\b", "analog-four-keys"),
    (r"\bModel:Cycles\b", "model-cycles"), (r"\bModel:Samples\b", "model-samples"),
    (r"\bMachinedrum\b", "machinedrum"), (r"\bMonomachine\b", "monomachine"),
]


def devs_in(text):
    return {slug for rx, slug in TEXT_DEVICE if re.search(rx, text or "")}


def lst(s):
    return [x for x in str(s or "").split(",") if x]


def ev_key(e):
    return min((EV_ORDER.get(x, 4) for x in lst(e)), default=4)


def tag(e):
    return " ".join(f"[{x}]" for x in lst(e)) or "[untagged]"


def tokens(text):
    return round(len(text) / 4)   # rough: ~4 characters per token for English technical text


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    q = lambda sql, *a: [dict(r) for r in con.execute(sql, a)]
    meta = {r["key"]: r["value"] for r in q("SELECT key, value FROM meta")}
    devices = q("SELECT slug, name, family, phase FROM devices")
    rules, facts = q("SELECT * FROM rules"), q("SELECT * FROM facts ORDER BY file, line")
    incidents, bugs = q("SELECT * FROM incidents"), q("SELECT * FROM stock_bugs")
    conflicts = q("SELECT * FROM conflicts WHERE status='open'")
    tasks = q("SELECT * FROM tasks WHERE status='open'")
    hyps = q("SELECT * FROM hypotheses WHERE status='open'")
    projects = q("SELECT * FROM projects")
    stamp = f"Data checked {meta.get('checked')}, research snapshot `{meta.get('research_snapshot')}`."
    has = lambda row, slug: slug in lst(row["devices"])

    index_rows = []
    for d in devices:
        slug, name = d["slug"], d["name"]
        safety = [r for r in rules if r["section"].startswith("A.")]
        dev_rules = [r for r in rules if not r["section"].startswith("A.") and has(r, slug)]
        d_bugs = [b for b in bugs if has(b, slug)]
        d_inc = [i for i in incidents if has(i, slug)]
        d_conf = [c for c in conflicts if has(c, slug)]
        d_tasks = [t for t in tasks if slug in devs_in(t["devices"])]
        d_hyps = [h for h in hyps if slug in devs_in(h["devices"])]
        d_facts = sorted([f for f in facts if has(f, slug)], key=lambda f: (ev_key(f["evidence"]), f["file"], f["line"]))
        recovery = [f for f in d_facts if f["file"].endswith(("recovery.md", "flash-procedure.md"))]
        d_proj = sorted([p for p in projects if has(p, slug) and p["kind"] in ("mod", "firmware", "loader", "emulator")],
                        key=lambda p: (p["kind"], p["name"].lower()))
        files = sorted({f["file"] for f in d_facts})

        head = [MARK, f"# {name}: agent context pack", "",
                f"{stamp} Generated from the Aggregat database; every item links back to the Markdown that is the "
                "source of truth. Everything here is second-hand: re-check addresses and byte patterns against the "
                "cited source before you rely on them. Evidence: `[hw]` seen on a real unit, `[emu]` emulator only, "
                "`[doc]` stated without a test result, `[?]` unclear or inferred.", ""]
        brief = []
        brief += ["## 1. Safety rules (all devices, never skip)", "",
                  "Titles only; full text in [AGENT-RULES.md](" + REPO + "hardware/AGENT-RULES.md).", ""]
        brief += [f"- **{r['id']}** {r['title']} {tag(r['evidence'])}" for r in safety] + [""]
        if dev_rules:
            brief += [f"## 2. Rules that name the {name}", ""]
            brief += [f"- **{r['id']}** ({r['section'].split(' ', 1)[0]}) {r['text']}" for r in dev_rules] + [""]
        brief += ["## 3. Recovery and flashing", ""]
        brief += ([f"- {tag(f['evidence'])} {f['text']} (`{f['fid']}`, [{f['file']}:{f['line']}]({REPO}{f['file']}#L{f['line']}))"
                   for f in recovery] or ["- Nothing device-specific recorded; read [recovery.md](" + REPO +
                                          "hardware/common/recovery.md) and treat recovery as unproven."]) + [""]
        brief += ["## 4. Bugs in Elektron's own OS (check before you blame your mod)", ""]
        brief += ([f"- **{b['id']}** {b['title']} ({b['device_os']}; {b['status']}). Workaround: {b['workaround']}" for b in d_bugs]
                  or ["- None recorded."]) + [""]
        brief += ["## 5. What went wrong on real units", ""]
        brief += ([f"- **{i['id']}** {i['title']}. Cause: {i['cause']} Fix: {i['fix']}"
                   + (f" Rules: {i['rules']}." if i["rules"] else "") for i in d_inc] or ["- None recorded."]) + [""]
        brief += ["## 6. Open conflicts (sources disagree)", ""]
        brief += ([f"- **{c['id']}** {c['topic']}: A) {c['a']} B) {c['b']}" for c in d_conf] or ["- None open."]) + [""]
        brief += ["## 7. Open tests and tasks you could settle", ""]
        brief += [f"- **{h['id']}** ({h['kind']}) {h['inference']} Test: {h['test']}" for h in d_hyps]
        brief += [f"- **{t['id']}** (needs {t['needs']}, effort {t['effort']}) {t['task']}" for t in d_tasks]
        if not d_hyps and not d_tasks:
            brief += ["- None open."]
        brief += ["", "Report results with the [test-result issue form](https://github.com/70b185/Aggregat/issues/new?template=test-result.yml).", ""]
        brief += ["## 8. Mods, firmware, loaders and emulators for this device", ""]
        brief += [f"- **{p['name']}** ({p['kind']}, {p['status'] or 'status unknown'}, tested: {p['tested'] or 'not stated'}"
                  + (f", base OS {p['base_os']}" if p["base_os"] else "") + ")" + (f" {p['repo']}" if p["repo"] else "")
                  for p in d_proj] or ["- None catalogued."]
        brief += ["", "## Fact files for this device", ""] + [f"- [{f}]({REPO}{f})" for f in files] + [""]

        full = list(brief)
        full += [f"## 9. All {len(d_facts)} facts, best evidence first", ""]
        for f in d_facts:
            full.append(f"- {tag(f['evidence'])} {f['text']} — `{f['fid']}` [{f['file']}:{f['line']}]({REPO}{f['file']}#L{f['line']})"
                        + (f" · {f['section']}" if f["section"] else ""))
        full.append("")

        b_txt = "\n".join(head + ["Brief version: rules, recovery, bugs, incidents and open questions. The full pack "
                                  f"[{slug}.md]({slug}.md) adds all facts.", ""] + brief)
        f_txt = "\n".join(head + [f"Full version. The brief one is [{slug}-brief.md]({slug}-brief.md).", ""] + full)
        write(CTX / f"{slug}-brief.md", b_txt)
        write(CTX / f"{slug}.md", f_txt)
        index_rows.append(f"| {name} | [{slug}-brief.md]({slug}-brief.md) | ~{tokens(b_txt):,} | [{slug}.md]({slug}.md) | "
                          f"~{tokens(f_txt):,} | {len(d_facts)} | {len(d_inc)} | {len(d_bugs)} |")

    write(CTX / "README.md", "\n".join([
        MARK, "# Context packs: one file per device", "",
        "For agents: load the **brief** pack before you touch a unit (safety rules, recovery, stock bugs, incidents, open "
        "questions, catalogued projects), and the **full** pack when you need the hardware facts too. Token counts are "
        "estimates (characters / 4). Each fact carries a stable id (`file-stem#hash`) that survives moved lines; cite it.",
        "", stamp, "",
        "| Device | Brief | Tokens | Full | Tokens | Facts | Incidents | Stock bugs |", "|---|---|---|---|---|---|---|---|",
        *index_rows, "",
        "Generated by `scripts/agent_packs.py` from `export/aggregat.sqlite`. The MCP server in `mcp/` serves the same "
        "data as queries.", ""]))

    # ------------------------------------------------------------ weak evidence
    weak = [f for f in facts if not lst(f["evidence"]) or lst(f["evidence"]) == ["?"]]
    by_file = {}
    for f in weak:
        by_file.setdefault(f["file"], []).append(f)
    out = [MARK, "# Weakly sourced facts", "",
           f"{len(weak)} of {len(facts)} facts carry no evidence tag or only `[?]`. Each is a small contribution waiting to "
           "happen: find the source and add the tag (`[hw]`, `[emu]` or `[doc]`), or turn the claim into a test in "
           "[HYPOTHESES.md](HYPOTHESES.md). Many untagged bullets are pointers or open questions, not claims; those just "
           "need `[?]` or a rewording.", "", stamp, "",
           f"- untagged: {sum(1 for f in weak if not lst(f['evidence']))}",
           f"- only `[?]`: {sum(1 for f in weak if lst(f['evidence']) == ['?'])}", ""]
    for file in sorted(by_file):
        out += [f"## [{file}](../{file}) ({len(by_file[file])})", ""]
        for f in by_file[file]:
            t = f["text"] if len(f["text"]) <= 220 else f["text"][:217].rsplit(" ", 1)[0] + " ..."
            out.append(f"- [L{f['line']}](../{file}#L{f['line']}) {tag(f['evidence'])} {t} `{f['fid']}`")
        out.append("")
    write(ROOT / "hardware" / "WEAK-EVIDENCE.md", "\n".join(out))

    # ------------------------------------------------------------ address map
    rows = q("SELECT address, value, fid, file, line, section, devices, evidence FROM addresses ORDER BY value, file, line")
    dev_name = {d["slug"]: d["name"] for d in devices}
    out = [MARK, "# Address map", "",
           "Every address that a fact names, per device, in address order. One line per address; the facts that name it "
           "follow, best evidence first. Two facts at the same address with different claims are worth a look: they may "
           "be a conflict (add it to [CONFLICTS.md](CONFLICTS.md)) or a RAM range two projects both use (rule area G8 in "
           "the [research map](../RESEARCH-MAP.md)). Addresses differ between OS versions; the fact text says which.", "",
           stamp, ""]
    for d in devices:
        drows = [r for r in rows if d["slug"] in lst(r["devices"])]
        if not drows:
            continue
        out += [f"## {dev_name[d['slug']]} ({len({r['address'] for r in drows})} addresses)", "",
                "| Address | Facts |", "|---|---|"]
        grouped = {}
        for r in drows:
            grouped.setdefault(r["value"], []).append(r)
        for v in sorted(grouped):
            rs = sorted(grouped[v], key=lambda r: (ev_key(r["evidence"]), r["file"], r["line"]))
            cells = "<br>".join(f"{tag(r['evidence'])} [{Path(r['file']).name}:{r['line']}](../{r['file']}#L{r['line']}) "
                                f"{r['section'].split(' / ')[-1]}".replace("|", "\\|") for r in rs)
            out.append(f"| `0x{v:08x}` | {cells} |")
        out.append("")
    write(ROOT / "hardware" / "ADDRESS-MAP.md", "\n".join(out))
    # ------------------------------------------------------------ llms.txt (https://llmstxt.org) for the website
    site = "https://70b185.github.io/Aggregat/"
    raw = "https://raw.githubusercontent.com/70b185/Aggregat/master/"
    c = json.loads(meta.get("counts", "{}"))
    llms = [
        "# Aggregat", "",
        f"> Index and agent knowledge base for community firmware, mods and tools on Elektron devices: {c.get('projects')} "
        f"projects, {c.get('facts')} hardware facts with evidence tags, {c.get('rules')} rules for agents, "
        f"{c.get('incidents')} incidents on real units and {c.get('stock_bugs')} bugs in Elektron's own OS. "
        "Metadata only, no firmware. CC0.", "",
        "Everything is second-hand; re-check addresses against the cited source. Evidence: [hw] real unit, [emu] "
        "emulator only, [doc] stated without a test, [?] inferred. Safety rules A1-A49 apply to every flash.", "",
        "## Start here",
        f"- [AGENTS.md]({raw}AGENTS.md): how agents should use this repository",
        f"- [Agent rules]({raw}hardware/AGENT-RULES.md): safety, legal and process rules, each with its evidence",
        f"- [Stock bugs]({raw}hardware/STOCK-BUGS.md): bugs in Elektron's OS, check before blaming a mod",
        f"- [Incidents]({raw}hardware/INCIDENTS.md): what went wrong on real units and the rule it taught",
        "", "## Context packs (one file per device; brief = before touching a unit, full = with all facts)"]
    llms += [f"- [{d['name']}]({raw}export/context/{d['slug']}-brief.md): brief; full: {raw}export/context/{d['slug']}.md"
             for d in devices]
    llms += ["", "## Data",
             f"- [SQLite database]({raw}export/aggregat.sqlite): all tables with full-text search over facts",
             f"- [JSON export]({raw}export/aggregat.json): the same tables as JSON",
             f"- [Export schema and example queries]({raw}export/README.md)",
             f"- [MCP server]({raw}mcp/README.md): query tools for agents",
             "", "## Optional",
             f"- [Research map]({raw}RESEARCH-MAP.md): what is known and open per device, shared goals",
             f"- [Feature overlap]({raw}FEATURE-OVERLAP.md): the same feature built on several devices",
             f"- [Address map]({raw}hardware/ADDRESS-MAP.md): every address named in a fact, per device",
             f"- [RAM tenancy]({raw}hardware/RAM-TENANCY.md): which mod platform uses which RAM range",
             f"- [Website]({site}): search, mod finder, network map", ""]
    write(ROOT / "llms.txt", "\n".join(llms))
    print(f"agent_packs: {len(devices)} devices, {len(weak)} weak facts, {len(rows)} address rows")


if __name__ == "__main__":
    main()
