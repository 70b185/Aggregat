#!/usr/bin/env python3
"""Write research/AGGREGAT_RESEARCH.md: a ready-to-copy file for projects that take part in Aggregat's research.

It carries a full copy of the current research state (goals, open tasks, hypotheses, open conflicts), so a project
that copies it records exactly the state its experiments started from. The snapshot is identified by its date and a
short hash of its content; when two copies differ, the hash shows they were taken from different states.

Usage: python3 scripts/research_snapshot.py      (run by the daily Action after build.py)
"""
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "research" / "AGGREGAT_RESEARCH.md"


def rows(path, first_cell):
    """Table rows whose first cell matches the regex first_cell, as lists of cell strings."""
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| "):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if re.fullmatch(first_cell, cells[0]):
            out.append(cells)
    return out


def links_absolute(text, base):
    """Turn relative Markdown links into links to the Aggregat repo, so they work inside another repo."""
    def fix(m):
        label, href = m.group(1), m.group(2)
        if re.match(r"[a-z]+:|#", href):
            return m.group(0)
        parts = (base + "/" + href).split("/")
        stack = []
        for p in parts:
            if p in ("", "."):
                continue
            if p == "..":
                if stack:
                    stack.pop()
                continue
            stack.append(p)
        return f"[{label}](https://github.com/70b185/Aggregat/blob/master/{'/'.join(stack)})"
    return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", fix, text)


def main():
    rmap = ROOT / "research" / "RESEARCH-MAP.md"
    hyp = ROOT / "hardware" / "HYPOTHESES.md"
    conf = ROOT / "hardware" / "CONFLICTS.md"
    goals = rows(rmap, r"G\d+")
    tasks = [r for r in rows(rmap, r"T\d+") if not r[1].startswith("~~")]
    hyps = rows(hyp, r"H\d+")
    opens = rows(conf, r"O\d+")

    body = ["## Goals (copied from Aggregat)", "", "| # | Goal | Where it stood | What would move it |", "|---|---|---|---|"]
    body += [f"| {g[0]} | {g[1]} | {g[2]} | {g[3]} |" for g in goals]
    body += ["", "## Open tasks", "", "| # | Task | Device | Needs | Effort |", "|---|---|---|---|---|"]
    body += [f"| {t[0]} | {t[1]} | {t[2]} | {t[3]} | {t[4]} |" for t in tasks]
    body += ["", "## Hypotheses (inferred, not yet shown on a unit)", "",
             "| # | Goal | Inference | Unit | Test |", "|---|---|---|---|---|"]
    body += [f"| {h[0]} | {h[1]} | {h[2]} | {h[4]} | {h[5]} |" for h in hyps]
    body += ["", "## Open conflicts between projects", "", "| # | Topic |", "|---|---|"]
    body += [f"| {o[0]} | {o[1]} |" for o in opens]
    snap = "\n".join(body) + "\n"
    snap = links_absolute(snap, "")
    digest = hashlib.sha256(snap.encode("utf-8")).hexdigest()[:12]
    reviewed = re.search(r"Last reviewed: (\d{4}-\d{2}-\d{2})", rmap.read_text(encoding="utf-8"))
    date = reviewed.group(1) if reviewed else "unknown"

    head = f"""<!-- Template for projects that take part in Aggregat's research: https://github.com/70b185/Aggregat
     Copy this file to the root of your repo as AGGREGAT_RESEARCH.md. Fill in "Our project", "What we work on" and
     "Results"; leave the copied state below as it is, so readers can see which state your experiments started from.
     To take a newer state, copy the snapshot part of a newer version of this file and note the date in "Copied state".
     Generated by scripts/research_snapshot.py; do not edit this copy in the Aggregat repo. -->
# Aggregat research: <your project>

This project takes part in the shared research of [Aggregat](https://github.com/70b185/Aggregat), an index and
knowledge base for community firmware on Elektron devices. Aggregat reads this file when it updates and merges
results by hand, with credit to this project. Taking part is voluntary and can stop at any time.

## Our project

| | |
|---|---|
| Project | <name, repo link> |
| Devices and OS versions we can test | <e.g. Digitakt II 1.17, Digitone II 1.12> |
| What we can do | <stock tests only / read-only probe builds / test builds> |
| Contact | <GitHub issues in this repo, or another way you prefer> |

## Copied state

| | |
|---|---|
| Aggregat state | research map reviewed {date}, snapshot `{digest}` |
| Copied on | <date you copied it> |

## What we work on

IDs from the copied state below (G = goal, T = task, H = hypothesis, O = open conflict), plus anything Aggregat
suggested for this project (see its research/PARTICIPANTS.md).

| ID | Since | Status | Note |
|---|---|---|---|
| <H2> | <date> | <planned / running / done> | <what you are trying> |

## Results

One row per result, also when it contradicts the inference. Evidence: `hw` = seen on a real unit, `emu` = in an
emulator, `doc` = read in code or documents.

| ID | Date | Unit and OS | Result | Evidence | Details |
|---|---|---|---|---|---|
| <H2> | <date> | <Digitakt II 1.17> | <one sentence: what happened> | <hw> | <link to notes, captures or photos> |

## Questions for Aggregat

<optional: anything you want the maintainers to check or explain>

---

# Copied state: Aggregat research, snapshot `{digest}` (research map reviewed {date})

"""
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(head + snap, encoding="utf-8")
    print(f"research snapshot {digest}: {len(goals)} goals, {len(tasks)} open tasks, {len(hyps)} hypotheses, "
          f"{len(opens)} open conflicts -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
